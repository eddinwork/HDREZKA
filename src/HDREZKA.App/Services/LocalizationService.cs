namespace HDREZKA.App.Services;

public sealed class LocalizationService
{
    public static LocalizationService Instance { get; } = new();

    private Dictionary<string, string> _strings = new();

    public event Action? LanguageChanged;

    public AppLanguage Current { get; private set; } = AppLanguage.Ru;

    public void Apply(AppLanguage language)
    {
        Current = language;
        _strings = language switch
        {
            AppLanguage.En => English,
            AppLanguage.Uk => Ukrainian,
            _ => Russian,
        };
        LanguageChanged?.Invoke();
    }

    public string Get(string key) => _strings.GetValueOrDefault(key, key);

    public string Get(string key, params object[] args)
    {
        try
        {
            return string.Format(System.Globalization.CultureInfo.InvariantCulture, Get(key), args);
        }
        catch (FormatException)
        {
            return Get(key);
        }
    }

